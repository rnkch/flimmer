// Package components finds the Web Awesome components the web UI uses and writes the imports
// that register them (assets/components.js). The bundler follows imports only, so a <wa-...> tag
// in a template that nobody imports stays an unknown element: unstyled and without behaviour.
package components

import (
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// File is where the generated imports go, relative to the web directory.
const File = "assets/components.js"

var tag = regexp.MustCompile(`<wa-([a-z][a-z0-9-]*)`)

// Scan lists the components used by the templates (.templ), the Go code that writes markup and
// the scripts below webDir, sorted. Components that only scripts create (no <wa-...> tag anywhere)
// are registered by hand in assets/components-extra.js. Vendored files, generated code, tests and
// command-line tools are skipped.
func Scan(webDir string) ([]string, error) {
	found := map[string]bool{}
	err := filepath.WalkDir(webDir, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(webDir, p)
		if d.IsDir() {
			switch rel {
			case "vendor", "cmd", "components", "bundle":
				return filepath.SkipDir
			}
			return nil
		}
		name := d.Name()
		switch {
		case strings.HasSuffix(name, "_test.go"), strings.HasSuffix(name, "_templ.go"),
			rel == File:
			return nil
		case strings.HasSuffix(name, ".templ"), strings.HasSuffix(name, ".go"),
			strings.HasSuffix(name, ".js"):
		default:
			return nil
		}
		b, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		for _, m := range tag.FindAllSubmatch(b, -1) {
			found[string(m[1])] = true
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	names := make([]string, 0, len(found))
	for n := range found {
		names = append(names, n)
	}
	sort.Strings(names)
	return names, nil
}

// Source is the content of the generated file for the given components.
func Source(names []string) string {
	var b strings.Builder
	b.WriteString("// Code generated by `go run ./internal/web/cmd/components`; DO NOT EDIT.\n")
	b.WriteString(
		"// Registers every Web Awesome component the templates, helpers and scripts use.\n",
	)
	for _, n := range names {
		fmt.Fprintf(&b, "import '@awesome.me/webawesome/components/%[1]s/%[1]s.js';\n", n)
	}
	return b.String()
}

// Generate scans webDir and writes the imports to webDir/File (only if they changed).
func Generate(webDir string) (names []string, err error) {
	if names, err = Scan(webDir); err != nil {
		return nil, err
	}
	dst := filepath.Join(webDir, File)
	src := Source(names)
	if old, err := os.ReadFile(dst); err == nil && string(old) == src {
		return names, nil
	}
	return names, os.WriteFile(dst, []byte(src), 0o644)
}
